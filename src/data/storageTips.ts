// Find a storage tip by item name (fuzzy match)
export function findStorageTip(itemName: string): StorageTipData | null {
  const normalizedSearch = itemName.toLowerCase().trim();
  
  // Exact match first
  const exactMatch = storageTipsDatabase.find(
    tip => tip.item.toLowerCase() === normalizedSearch
  );
  if (exactMatch) return exactMatch;
  
  // Partial match (item name contains search or search contains item name)
  const partialMatch = storageTipsDatabase.find(
    tip => tip.item.toLowerCase().includes(normalizedSearch) || 
           normalizedSearch.includes(tip.item.toLowerCase())
  );
  if (partialMatch) return partialMatch;
  
  // Word match (any word in item name matches)
  const words = normalizedSearch.split(/\s+/);
  const wordMatch = storageTipsDatabase.find(tip => {
    const tipWords = tip.item.toLowerCase().split(/\s+/);
    return words.some(word => tipWords.some(tipWord => 
      tipWord.includes(word) || word.includes(tipWord)
    ));
  });
  
  return wordMatch || null;
}

// Get estimated shelf life based on category
export function getEstimatedShelfLife(category: 'pantry' | 'refrigerator' | 'freezer'): string {
  switch (category) {
    case 'pantry':
      return '1-2 years if stored properly';
    case 'refrigerator':
      return '3-7 days typically';
    case 'freezer':
      return '3-6 months for best quality';
    default:
      return 'Varies by item';
  }
}
